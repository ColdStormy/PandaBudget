def plural(one, other, zero=None):
    parts = []
    if zero is not None:
        parts.append("=0{%s}" % zero)
    parts.append("=1{%s}" % one)
    parts.append("other{%s}" % other)
    return "{count, plural, %s}" % " ".join(parts)

